// as they are: they are the names of the controls in the music vocabulary used in Brazil,
// and the docs name them the same way. So do the words producers say in English (pad,
// pluck, lead, chorus, gate), parameter names (tone), the language's own words and "Made
// with Untzel", which the exported card shows in every language; "Tap tempo" and the
// fader's "Off", the words on the hardware. The key is written as the text writes it
// ("a minor") on the transport, the cards and the key picker, in every language,
// so one form reads everywhere.
// "Next bar" is "próximo compasso": "virada" alone reads as a drum fill to a Brazilian
// musician. pnpm i18n:check fails when a key of the source has no entry here.
