// The instrument index, a step of pnpm generate: reads
// instruments/*/manifest.json with the rule of packages/dsp/build.rs (the folders with a
// manifest.json, in order of name) and writes, outside git:
//   packages/instrument-index/src/generated/manifests.ts   every manifest, and the sample packs
//   apps/web/src/generated/voice-packs.ts                  the composition's sample pack URLs
// Writes a file only when its content changes. --check writes nothing and fails when a file
// is stale. Adding an instrument is its folder in instruments/; no list is edited by hand.
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { pathToFileURL } from "node:url";
import { REPO } from "./lib.mjs";
export const MANIFESTS_FILE = "packages/instrument-index/src/generated/manifests.ts";
export const VOICE_PACKS_FILE = "apps/web/src/generated/voice-packs.ts";
const PACK = "samples/v1/pack.json";
const byCodeUnit = (left, right) => (left < right ? -1 : left > right ? 1 : 0);
/** "fm-bass" → "fmBass": the identifier of a manifest's default import. */
export const identifierOf = (name) => name.replace(/-([a-z0-9])/g, (whole, letter) => letter.toUpperCase());
/**
 * The instruments of a folder: every sub-folder with a manifest.json, in order of the
 * manifest's name (packages/dsp/build.rs, read_instruments), with whether it has a sample pack.
 */
export function readInstruments(root, fs = { readdirSync, existsSync, readFileSync }) {
  return fs
    .readdirSync(root, { withFileTypes: true })
    .filter((entry) => entry.isDirectory() && fs.existsSync(join(root, entry.name, "manifest.json")))
    .map((entry) => {
      const manifest = JSON.parse(fs.readFileSync(join(root, entry.name, "manifest.json"), "utf8"));
      return { folder: entry.name, name: manifest.name, group: manifest.group, kind: manifest.kind, hasPack: fs.existsSync(join(root, entry.name, PACK)) };
    })
    .sort((left, right) => byCodeUnit(left.name, right.name));
}
/**
 * The fetch order of v1.0.0: melodic packs, then voices, then percussion, by name within each.
 * The SamplePackLoader fires both fetches of each pack in the order of the array, and until a
 * pack arrives its tracks play with the synthesized voice; changing this order is another
 * change, with its own review.
 */
const packRank = (instrument) => (instrument.group === "voices" ? 1 : instrument.kind === "drum" ? 2 : 0);
export function fetchOrder(instruments) {
  return instruments.filter((instrument) => instrument.hasPack).sort((left, right) => packRank(left) - packRank(right) || byCodeUnit(left.name, right.name));
}
const HEADER = "// Generated by tools/harness/generate-instruments.mjs from instruments/*/manifest.json: do not edit.\n";
/** packages/instrument-index/src/generated/manifests.ts */
export function renderManifests(instruments) {
  const imports = instruments.map((instrument) => `import ${identifierOf(instrument.name)} from "../../../../instruments/${instrument.folder}/manifest.json";`);
  const list = instruments.map((instrument) => `  ${identifierOf(instrument.name)},`);
  const packs = instruments.filter((instrument) => instrument.hasPack).map((instrument) => `  "${instrument.name}",`);
  return [
    HEADER.trimEnd(),
    "// Typed as unknown: every manifest goes through parseManifest before createRegistry.",
    ...imports,
    "/** Every instrument of instruments/, in order of name (the order of packages/dsp/build.rs). */",
    "export const manifests: readonly unknown[] = [",
    ...list,
    "];",
    "/** The instruments with a recorded sample pack (samples/v1/pack.json), in order of name. */",
    "export const samplePackInstruments: readonly string[] = [",
    ...packs,
    "];",
    "",
  ].join("\n");
}
/** apps/web/src/generated/voice-packs.ts */
export function renderVoicePacks(instruments) {
  const packs = fetchOrder(instruments);
  const imports = packs.flatMap((instrument) => {
    const id = identifierOf(instrument.name);
    const base = `../../../../instruments/${instrument.folder}/samples/v1/pack`;
    return [`import ${id}Manifest from "${base}.json?url";`, `import ${id}Audio from "${base}.opus?url";`];
  });
  const entries = packs.map((instrument) => {
    const id = identifierOf(instrument.name);
    return `  { instrument: "${instrument.name}", manifestUrl: ${id}Manifest, audioUrl: ${id}Audio },`;
  });
  return [
    HEADER.trimEnd(),
    "// The recorded packs as Vite asset URLs, in the fetch order of v1.0.0 (melodic, voices, then",
    "// percussion; by name within each). Imported by the boot chunk only, so the initial bundle",
    "// carries neither the URLs nor the loader; the audio is fetched only when a program uses one",
    "// of the instruments.",
    'import type { SamplePackSource } from "@untzel/audio/main";',
    ...imports,
    "export const VOICE_PACKS: readonly SamplePackSource[] = [",
    ...entries,
    "];",
    "",
  ].join("\n");
}
/** The two generated files for a repository root. */
export function generatedFiles(root, fs) {
  const instruments = readInstruments(join(root, "instruments"), fs);
  return [
    { path: MANIFESTS_FILE, text: renderManifests(instruments) },
    { path: VOICE_PACKS_FILE, text: renderVoicePacks(instruments) },
  ];
}
/** The generated files whose text on disk differs from what instruments/ gives. */
export function staleFiles(files, read) {
  return files.filter((file) => read(file.path) !== file.text);
}
function main() {
  const read = (path) => (existsSync(join(REPO, path)) ? readFileSync(join(REPO, path), "utf8") : null);
  const stale = staleFiles(generatedFiles(REPO), read);
  if (!process.argv.includes("--check")) {
    for (const file of stale) {
      mkdirSync(dirname(join(REPO, file.path)), { recursive: true });
      writeFileSync(join(REPO, file.path), file.text);
    }
    return;
  }
  if (stale.length > 0) {
    console.error(`generate-instruments: ${stale.map((file) => file.path).join(", ")} is stale; run pnpm generate`);
    process.exit(1);
  }
}
if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) main();
