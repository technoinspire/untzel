// Every source file starts with the CPAL-1.0 header (CONTRIBUTING.md, the license header
// standard), and a file "derived from" third-party code is listed in THIRD_PARTY.md.
//   node tools/headers/check-headers.mjs          fails when a header is missing
//   node tools/headers/check-headers.mjs --fix    inserts the missing headers
// Files are the ones git tracks plus untracked files that are not ignored, so generated
// output (packages/language/src/generated/, packages/dsp/dist/, .cache/) never counts.

import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { extname } from "node:path";
import { attributionProblems, thirdPartySections } from "./third-party.mjs";

const SPDX = "SPDX-License-Identifier: CPAL-1.0";
const COPYRIGHT = "Copyright (c) 2026 Techno Inspire. See LICENSE and ATTRIBUTION.md.";

/** Comment syntax per extension: how each of the two header lines is written. */
const LINE_COMMENT = (text) => `// ${text}`;
const BLOCK_COMMENT = (text) => `/* ${text} */`;
const HASH_COMMENT = (text) => `# ${text}`;
const HTML_COMMENT = (text) => `<!-- ${text} -->`;
const SYNTAX = new Map([
  [".ts", LINE_COMMENT],
  [".mts", LINE_COMMENT],
  [".js", LINE_COMMENT],
  [".mjs", LINE_COMMENT],
  [".cjs", LINE_COMMENT],
  [".rs", LINE_COMMENT],
  [".wgsl", LINE_COMMENT],
  [".glsl", LINE_COMMENT],
  [".grammar", LINE_COMMENT],
  [".css", BLOCK_COMMENT],
  [".py", HASH_COMMENT],
  [".sh", HASH_COMMENT],
  [".html", HTML_COMMENT],
]);

/**
 * Excluded on purpose, with the reason. Everything else with a known extension needs the
 * header. Templates are music the user reads and edits: a header there would show in the
 * editor and change the seed of every shared link.
 */
const EXCLUDED = [
  { pattern: /(^|\/)generated\//, reason: "generated by lezer-generator" },
  { pattern: /^packages\/dsp\/dist\//, reason: "WASM build output" },
  { pattern: /\.untzel$/, reason: "music templates, read and edited by the user" },
];

function listFiles() {
  const output = execFileSync("git", ["ls-files", "--cached", "--others", "--exclude-standard", "-z"], {
    encoding: "utf8",
    stdio: ["ignore", "pipe", "inherit"],
  });
  return output.split("\0").filter((path) => path.length > 0);
}

function expectedHeader(path) {
  const comment = SYNTAX.get(extname(path));
  return comment === undefined ? null : [comment(SPDX), comment(COPYRIGHT)];
}

/** A shebang or an HTML doctype must stay on the first line; the header follows it. */
function splitFirstLine(text) {
  if (!text.startsWith("#!") && !/^<!doctype /i.test(text)) return { shebang: "", body: text };
  const end = text.indexOf("\n") + 1;
  return { shebang: text.slice(0, end), body: text.slice(end) };
}

function hasHeader(body, header) {
  const lines = body.split("\n", 2).map((line) => line.replace(/\r$/, ""));
  return lines[0] === header[0] && lines[1] === header[1];
}

function main() {
  const fix = process.argv.includes("--fix");
  const missing = [];
  const unattributed = [];
  const sections = thirdPartySections(existsSync("THIRD_PARTY.md") ? readFileSync("THIRD_PARTY.md", "utf8") : "");
  let checked = 0;
  for (const path of listFiles()) {
    if (EXCLUDED.some(({ pattern }) => pattern.test(path))) continue;
    const header = expectedHeader(path);
    if (header === null) continue;
    let text;
    try {
      text = readFileSync(path, "utf8");
    } catch {
      continue; // deleted in the working tree
    }
    checked += 1;
    unattributed.push(...attributionProblems(path, text, sections));
    const { shebang, body } = splitFirstLine(text);
    if (hasHeader(body, header)) continue;
    if (fix) {
      writeFileSync(path, `${shebang}${header.join("\n")}\n\n${body}`);
    } else {
      missing.push(path);
    }
  }
  if (missing.length > 0) {
    console.error(`check:headers FAIL: ${missing.length} of ${checked} source files lack the CPAL-1.0 header:`);
    for (const path of missing) console.error(`  ${path}`);
    console.error("Run: node tools/headers/check-headers.mjs --fix");
    process.exit(1);
  }
  if (unattributed.length > 0) {
    console.error(`check:headers FAIL: ${unattributed.length} derived file(s) without their THIRD_PARTY.md entry:`);
    for (const problem of unattributed) console.error(`  ${problem}`);
    process.exit(1);
  }
  console.log(`check:headers PASS: ${checked} source files carry the CPAL-1.0 header${fix ? " (fixed)" : ""}.`);
}

main();
